-- R4: class date ranges + centre term presets; the rolling-window session
-- generator is removed (docs/00-master-product-spec.md §5.1 "Class periods
-- and centre terms", docs/03-build-order.md "R4").
--
-- No production data exists when this migration runs: every database it
-- targets holds seed/demo data only.

-- ─────────────────────────────────────────────────────────────────────────
-- 1. ClassGroup.startDate / endDate — the class's period, date-only, stored
--    as a UTC-midnight day marker exactly like Session.date / Holiday.date.
--    Added nullable, backfilled, then made NOT NULL:
--      startDate = the class's earliest session date, else its createdAt day;
--      endDate   = the class's latest session date, else startDate.
--    So every existing class keeps exactly the sessions it already has, and
--    nothing new is generated by the migration itself.
-- ─────────────────────────────────────────────────────────────────────────

ALTER TABLE "ClassGroup" ADD COLUMN "startDate" TIMESTAMP(3),
ADD COLUMN "endDate" TIMESTAMP(3);

UPDATE "ClassGroup" AS cg
SET "startDate" = COALESCE(
  (SELECT MIN(s."date") FROM "Session" AS s WHERE s."classGroupId" = cg."id"),
  date_trunc('day', cg."createdAt")
);

UPDATE "ClassGroup" AS cg
SET "endDate" = COALESCE(
  (SELECT MAX(s."date") FROM "Session" AS s WHERE s."classGroupId" = cg."id"),
  cg."startDate"
);

ALTER TABLE "ClassGroup" ALTER COLUMN "startDate" SET NOT NULL,
ALTER COLUMN "endDate" SET NOT NULL;

-- ─────────────────────────────────────────────────────────────────────────
-- 2. CenterTerm — a centre's own term presets. A preset's dates are COPIED
--    onto a class when the class form picks it; there is no FK from
--    ClassGroup, so editing or deleting a term never moves a class. Name
--    uniqueness (per centre, case-insensitive) is enforced by lib/db/terms.ts.
-- ─────────────────────────────────────────────────────────────────────────

-- CreateTable
CREATE TABLE "CenterTerm" (
    "id" TEXT NOT NULL,
    "centerId" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "startDate" TIMESTAMP(3) NOT NULL,
    "endDate" TIMESTAMP(3) NOT NULL,
    "active" BOOLEAN NOT NULL DEFAULT true,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "CenterTerm_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE INDEX "CenterTerm_centerId_idx" ON "CenterTerm"("centerId");

-- AddForeignKey
ALTER TABLE "CenterTerm" ADD CONSTRAINT "CenterTerm_centerId_fkey" FOREIGN KEY ("centerId") REFERENCES "Center"("id") ON DELETE CASCADE ON UPDATE CASCADE;
